"""Offline, real Chromium regression for the default reader. Optional Playwright only."""
import argparse
import importlib.util
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, Error

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('builder', ROOT / 'scripts/build_report.py')
builder = importlib.util.module_from_spec(spec); spec.loader.exec_module(builder)


def run(output):
    output.mkdir(parents=True, exist_ok=True)
    generic = output / 'focus-example.html'
    builder.build(ROOT / 'examples/focus-changes.json', generic, strict=True)
    continuous = output / 'continuous-changes.html'
    legacy_data = json.loads((ROOT/'examples/focus-changes.json').read_text(encoding='utf-8'))
    legacy_data['readingMode']='continuous'
    builder.validate(legacy_data)
    continuous.write_text(builder.Renderer(legacy_data, ROOT/'examples').render(),encoding='utf-8')
    records, errors, requests = [], [], []
    def check(value, name):
        records.append({'name':name,'pass':bool(value)})
        assert value, name
    def watch(page):
        page.on('pageerror', lambda e: errors.append(str(e)))
        page.on('request', lambda r: requests.append(r.url) if r.url.startswith(('http:','https:')) else None)
    def active(page): return page.locator('.shell>[data-chapter]:visible')
    with sync_playwright() as p:
        try: browser=p.chromium.launch()
        except Error: browser=p.chromium.launch(channel='chrome')
        try:
            context=browser.new_context(offline=True,viewport={'width':1440,'height':1000})
            page=context.new_page(); watch(page)
            page.goto(generic.as_uri())
            check(active(page).count()==1 and active(page).get_attribute('id')=='overview','default shows only core conclusion')
            check(page.locator('#report-outline').evaluate('(e)=>e.scrollHeight<=e.clientHeight+1'),'desktop navigation fits one screen')
            check(page.locator('#report-outline nav a').count()==4,'only top-level titles in navigation')
            page.screenshot(path=str(output/'generic-desktop.png'))
            graph=page.locator('#overview [data-change-diagram]')
            for state in ['before','after','change']:
                graph.locator(f'[data-diagram-view="{state}"]').click()
                scene=graph.locator(f'[data-diagram-state="{state}"]')
                check(graph.locator('.diagram-scene:visible').count()==1,f'{state} selects one diagram view')
                check(scene.locator('[data-node-id="sdk"]').count()==(0 if state=='before' else 1),f'{state} node scope is correct')
                page_label=scene.locator('[data-node-id="page"]>text').text_content().replace('\n','')
                check('原页面＋状态查询'==page_label if state!='before' else page_label=='原页面',f'{state} visible label is correct')
            check(graph.locator('[data-legend-shape="process"]').count()==1 and graph.locator('[data-legend-shape="decision"]').count()==0,'legend contains actual shapes only')
            check('新增' in graph.locator('.diagram-change-key').inner_text(),'changes have always-visible non-color labels')
            legend=graph.locator('.change-diagram-legend')
            check(legend.evaluate('(e)=>e.open') and legend.locator('[data-legend-shape="process"]').is_visible(),'legend starts expanded with explanations visible')
            legend.locator('summary').click()
            check(not legend.locator('[data-legend-shape="process"]').is_visible(),'reader can collapse the expanded legend')
            legend.locator('summary').click()
            nav=page.locator('#report-outline nav').inner_text()
            page.locator('#report-outline nav a[href="#bounds"]').click()
            check(active(page).get_attribute('id')=='bounds' and not page.locator('#chapter-dialog').is_visible(),'navigation replaces main area without chapter overlay')
            check(page.locator('#bounds h2').evaluate('(e)=>e===document.activeElement'),'chapter heading receives keyboard focus')
            check(page.locator('#bounds h2').evaluate('(e)=>parseFloat(getComputedStyle(e).fontSize)')>page.locator('#bounds .section-subtitle').evaluate('(e)=>parseFloat(getComputedStyle(e).fontSize)'),'subtitle is visually secondary')
            check(page.locator('#bounds h2 .heading-help').count()==0 and page.locator('#bounds .nav-subtitle').is_visible(),'main title has a visible secondary subtitle without question controls')
            heading_note=page.locator('#report-outline nav li').filter(has=page.locator('a[href="#bounds"]')).locator('.nav-note')
            heading_help=heading_note.locator('.heading-help')
            heading_tip=heading_note.locator('.heading-tooltip')
            check(page.locator('#report-outline nav a button').count()==0,'subtitle help is a sibling of the navigation link')
            check(not heading_tip.is_visible(),'navigation hint starts closed while main subtitle is visible')
            check(heading_tip.inner_text()==page.locator('#bounds .nav-subtitle').inner_text(),'navigation hint and main subtitle use the same text')
            before_help=page.url
            heading_help.hover();check(heading_tip.is_visible(),'navigation help hover reveals the corresponding subtitle')
            check(heading_tip.evaluate('(e)=>{const r=e.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.top>=0&&r.bottom<=innerHeight}'),'navigation tooltip remains within viewport without clipping')
            page.keyboard.press('Escape');check(not heading_tip.is_visible(),'Escape dismisses heading explanation')
            heading_help.focus();check(heading_tip.is_visible(),'heading explanation supports keyboard focus')
            heading_help.click();heading_help.click();check(not heading_tip.is_visible(),'second heading click closes touch explanation')
            check(page.url==before_help and active(page).get_attribute('id')=='bounds','help does not navigate or change the selected panel')
            page.go_back()
            check(active(page).get_attribute('id')=='overview','browser back restores previous chapter')
            page.go_forward()
            check(active(page).get_attribute('id')=='bounds','browser forward restores chapter')
            citation=page.locator('#bounds .section-summary .evidence-ref').first
            citation.hover(); page.wait_for_timeout(100)
            check(page.locator('#citation-popover').is_visible() and '虚构设计' in page.locator('#citation-popover').inner_text(),'citation hover previews source summary')
            page.keyboard.press('Escape')
            citation.focus()
            check(page.locator('#citation-popover').is_visible(),'citation keyboard focus previews source')
            target=citation.get_attribute('href')[1:]
            citation.click()
            check(page.locator('#'+target).evaluate('(e)=>e.closest("[data-chapter]").id')=='bounds','citation jumps to sources in same chapter')
            check(page.locator('#'+target).evaluate('(e)=>e===document.activeElement'),'source destination receives focus')
            term=page.locator('#bounds a.term').first
            term.hover(); check(page.locator('#term-popover').is_visible(),'existing underlined terminology preview works')
            term.click(); check(page.locator('#term-dialog').is_visible(),'term opens full definition')
            page.keyboard.press('Escape'); check(term.evaluate('(e)=>e===document.activeElement'),'term close returns focus')
            page.locator('#bounds details[data-fold]>summary').click()
            image=page.locator('#bounds .report-figure img')
            preview=page.locator('#figure-dialog')
            image.click(); check(preview.is_visible(),'image preview opens')
            preview.locator('img').click(); check(not preview.is_visible(),'second image click closes preview')
            image.click(); page.mouse.click(1,1); check(not preview.is_visible(),'overlay click closes preview')
            image.click(); preview.locator('[data-close-dialog]').click(); check(not preview.is_visible(),'close button closes preview')
            image.focus(); page.keyboard.press('Enter'); page.keyboard.press('Escape')
            check(not preview.is_visible() and image.evaluate('(e)=>e===document.activeElement'),'image keyboard close restores focus')
            page.locator('#report-outline nav a[href="#checks"]').click()
            shapes=page.locator('#checks [data-legend-shape]').evaluate_all('(es)=>es.map(e=>e.dataset.legendShape)')
            check(set(shapes)=={'process','decision','store','data','terminator'},'flow legend explains all actual semantic shapes')
            check(page.locator('#checks .diagram-scene').count()==1,'unchanged flow has one view, without useless switches')
            page.screenshot(path=str(output/'generic-flow-desktop.png'))
            for width,height in [(1440,720),(390,844)]:
                page.set_viewport_size({'width':width,'height':height})
                page.locator('#report-outline nav a[href="#overview"]').click()
                check(page.evaluate('document.documentElement.scrollWidth<=innerWidth'),f'{width}px has no page overflow')
                check(page.locator('#report-outline').evaluate('(e)=>e.scrollHeight<=e.clientHeight+1'),f'{width}px navigation does not scroll')
                check(page.locator('#report-outline nav').inner_text()==nav,f'{width}px retains navigation structure')
                check(page.locator('#overview').evaluate('(e)=>e.getBoundingClientRect().left>=0'),f'{width}px main content is accessible')
                mobile_help=page.locator('#report-outline nav .heading-help').first
                mobile_help.click()
                mobile_tip=mobile_help.locator('..').locator('.heading-tooltip')
                check(mobile_tip.is_visible() and mobile_tip.evaluate('(e)=>{const r=e.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth}'),f'{width}px sidebar help supports touch without overflow')
                mobile_help.click()
                check(not mobile_tip.is_visible(),f'{width}px second touch closes sidebar help')
                page.screenshot(path=str(output/f'generic-{width}.png'))
            page.locator('#report-outline nav a[href="#bounds"]').click()
            page.emulate_media(media='print')
            check(page.evaluate('matchMedia("print").matches'),'generic PDF explicitly uses print media')
            page.pdf(path=str(output/'generic-full-print.pdf'),format='A4',print_background=True)
            check(active(page).count()==page.locator('.shell>[data-chapter]').count(),'print contains every chapter despite selected panel')
            check(page.locator('#overview .diagram-scene:visible').count()==3,'print includes all change views')
            check(page.locator('#bounds .report-figure img').is_visible(),'print expands folded details')
            check(page.locator('#bounds .nav-subtitle').is_visible(),'print restores subtitles beside their content')
            page.emulate_media(media='screen')
            check(active(page).count()==1 and active(page).get_attribute('id')=='bounds','printing preserves screen selection')
            page.goto(generic.as_uri()+'#checks')
            check(active(page).get_attribute('id')=='checks','direct hash loads the intended chapter')
            ids=page.locator('[id]').evaluate_all('(es)=>es.map(e=>e.id)')
            check(len(ids)==len(set(ids)),'integrated page ids are unique')
            check(page.locator('.section-sources p,.section-sources details').count()==0,'sources list does not duplicate detailed evidence')
            check(page.locator('#appendix .evidence-table').count()==1,'complete evidence inventory appears once in appendix')
            page.set_viewport_size({'width':1440,'height':1000})
            page.locator('.nav-highlights a[href="#bounds"]').click()
            check(active(page).get_attribute('id')=='bounds','global highlight navigates to its topic')
            page.goto(continuous.as_uri())
            page.locator('#report-outline nav a[href="#overview"]').click()
            legacy_graph=page.locator('#chapter-dialog [data-change-diagram]')
            legacy_graph.locator('[data-diagram-view="before"]').click()
            check(legacy_graph.locator('[data-diagram-state="before"]').is_visible() and legacy_graph.locator('[data-diagram-state="change"]').is_hidden(),'optional continuous overlay also switches change views')
            check(legacy_graph.locator('[data-diagram-view="before"]').evaluate('(e)=>document.getElementById(e.getAttribute("aria-controls")).closest("dialog").id')=='chapter-dialog','cloned diagram controls refer to cloned scene')
            page.keyboard.press('Escape')
            nojs=browser.new_context(offline=True,java_script_enabled=False,viewport={'width':390,'height':844})
            np=nojs.new_page(); watch(np); np.goto(generic.as_uri())
            check(active(np).count()==4,'no-script retains all chapters')
            check(np.locator('#overview .diagram-scene:visible').count()==3,'no-script retains all change states')
            check(not np.locator('.diagram-state-controls').first.is_visible(),'no-script hides unavailable diagram controls')
            check(np.locator('.change-diagram-legend').first.evaluate('(e)=>e.open'),'no-script also starts with expanded legend')
            check(np.locator('#bounds .nav-subtitle').is_visible(),'no-script retains readable section subtitles')
            np.locator('#report-outline nav a[href="#bounds"]').click()
            check(np.url.endswith('#bounds'),'no-script uses ordinary anchors')
            np.screenshot(path=str(output/'generic-nojs.png'))
            nojs.close()
            check(not errors,'no script errors')
            check(not requests,'no external runtime requests')
        finally:
            browser.close()
            (output/'focus-results.json').write_text(json.dumps({'checks':records,'errors':errors,'externalRequests':requests},ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps({'checks':len(records),'passed':sum(r['pass'] for r in records)},ensure_ascii=False))


if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--output',type=Path,required=True)
    args=parser.parse_args()
    run(args.output.resolve())
